create table if not exists public.inventory_items (
 id bigint generated by default as identity primary key,
 item_name text not null unique,
 sort_order integer not null default 0,
 active boolean not null default true
);

create table if not exists public.daily_stock (
 id bigint generated by default as identity primary key,
 stock_date date not null,
 item_id bigint not null references public.inventory_items(id) on delete cascade,
 stock_balance numeric(12,2) not null default 0 check (stock_balance >= 0),
 stock_in numeric(12,2) not null default 0 check (stock_in >= 0),
 stock_out numeric(12,2) not null default 0 check (stock_out >= 0),
 stock_total numeric(12,2) generated always as (stock_balance + stock_in - stock_out) stored,
 stock_usage numeric(12,2) generated always as (stock_out) stored,
 updated_by uuid references auth.users(id),
 updated_at timestamptz not null default now(),
 unique(stock_date,item_id)
);

create table if not exists public.stock_activity (
 id bigint generated by default as identity primary key,
 created_at timestamptz not null default now(),
 stock_date date,
 item_id bigint,
 item_name text,
 action text not null,
 staff_id uuid,
 staff_email text
);

create or replace function public.log_stock_change()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_name text; v_email text;
begin
 select item_name into v_name from public.inventory_items where id=coalesce(new.item_id,old.item_id);
 select email into v_email from auth.users where id=auth.uid();
 insert into public.stock_activity(stock_date,item_id,item_name,action,staff_id,staff_email)
 values(coalesce(new.stock_date,old.stock_date),coalesce(new.item_id,old.item_id),v_name,
 case when tg_op='INSERT' then 'created stock entry' else 'updated stock entry' end,auth.uid(),v_email);
 new.updated_at=now();
 return new;
end $$;

drop trigger if exists daily_stock_audit on public.daily_stock;
create trigger daily_stock_audit before insert or update on public.daily_stock
for each row execute function public.log_stock_change();

alter table public.inventory_items enable row level security;
alter table public.daily_stock enable row level security;
alter table public.stock_activity enable row level security;

create policy "authenticated staff can read items" on public.inventory_items for select to authenticated using (true);
create policy "authenticated staff can read daily stock" on public.daily_stock for select to authenticated using (true);
create policy "authenticated staff can insert daily stock" on public.daily_stock for insert to authenticated with check (auth.uid()=updated_by);
create policy "authenticated staff can update daily stock" on public.daily_stock for update to authenticated using (true) with check (auth.uid()=updated_by);
create policy "authenticated staff can read activity" on public.stock_activity for select to authenticated using (true);

alter publication supabase_realtime add table public.daily_stock;
